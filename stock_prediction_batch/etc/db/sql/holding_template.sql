-- このファイルは UTF-8 で書いている。Windows の psql は既定の文字コードが違う場合があるので、明示する
SET client_encoding = 'UTF8';

-- ---------------------------------------------------------------------
-- 買ったとき: 1回の購入につき1行を登録する
-- 同じ銘柄を2回に分けて買った場合は、2行に分ける
-- ---------------------------------------------------------------------
INSERT INTO holding (code, buy_price, quantity, buy_date, note)
VALUES ('<銘柄コード5桁>', <買値>, <株数>, '<購入日 YYYY-MM-DD>', '<メモ>');

-- ---------------------------------------------------------------------
-- 売ったとき: 行は削除せず、売却日と売値を入れる
-- 保有ID(holding_id)は、下の「保有中の銘柄を確認する」で調べる
-- ---------------------------------------------------------------------
UPDATE holding
SET sell_date = '<売却日 YYYY-MM-DD>', sell_price = <売値>, updated_at = now()
WHERE holding_id = <保有ID>;

-- ---------------------------------------------------------------------
-- 保有中の銘柄を確認する
-- ---------------------------------------------------------------------
SELECT h.holding_id, h.code, m.name, h.buy_price, h.quantity, h.buy_date, h.note
FROM holding h
LEFT JOIN stock_master m ON m.code = h.code
WHERE h.sell_date IS NULL
ORDER BY h.buy_date, h.holding_id;
